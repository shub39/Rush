package com.shub39.rush.shared.logic.util

import java.security.MessageDigest
import javax.crypto.Cipher
import javax.crypto.spec.SecretKeySpec

internal actual fun md5Hex(input: ByteArray): String =
    MessageDigest.getInstance("MD5").digest(input).toHex()

internal actual fun aesEcbEncrypt(input: ByteArray, key: ByteArray): ByteArray {
    val cipher = Cipher.getInstance("AES/ECB/PKCS5Padding")
    cipher.init(Cipher.ENCRYPT_MODE, SecretKeySpec(key, "AES"))
    return cipher.doFinal(input)
}
