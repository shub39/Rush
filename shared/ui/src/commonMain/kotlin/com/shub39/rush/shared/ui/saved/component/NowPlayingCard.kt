import com.shub39.rush.shared.core.dataclasses.ExtractedColors
import com.shub39.rush.shared.core.dataclasses.SongUi
import com.shub39.rush.shared.ui.component.ArtFromUrl

/** The compact pill showing the song that is currently loaded in the lyrics screen. */
@Composable
fun NowPlayingCard(
    nowPlaying: SongUi,
    colors: ExtractedColors,
    onClick: () -> Unit,
    modifier: Modifier = Modifier,
) {
    Card(
        onClick = onClick,
        shape = CircleShape,
        modifier = modifier,
        colors =
            CardDefaults.cardColors(
                contentColor = Color(colors.cardContentMuted),
                containerColor = Color(colors.cardBackgroundMuted),
            ),
    ) {
        Row(
            verticalAlignment = Alignment.CenterVertically,
            horizontalArrangement = Arrangement.spacedBy(12.dp),
            modifier = Modifier.padding(8.dp),
        ) {
            ArtFromUrl(
                imageUrl = nowPlaying.artUrl,
                modifier = Modifier.size(48.dp).clip(CircleShape),
            )

            Column {
                Text(
                    text = nowPlaying.title,
                    style = MaterialTheme.typography.titleMedium,
                    fontWeight = FontWeight.Bold,
                    maxLines = 1,
                    overflow = TextOverflow.Ellipsis,
                )

                Text(
                    text = nowPlaying.artists,
                    style = MaterialTheme.typography.bodyMedium,
                    maxLines = 1,
                    overflow = TextOverflow.Ellipsis,
                )
            }
        }
    }
}
